//! The window's languages. Each language is a list of (key, text); a missing key falls back to English, then to the key itself.
//! `{0}`, `{1}` in a text are replaced by the arguments of `tr_args`.

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Lang {
    En,
    ZhHans,
    ZhHant,
    Ja,
    Ko,
    De,
    Fr,
    Es,
    Ru,
}

impl Lang {
    pub const ALL: [Lang; 9] = [Lang::En, Lang::ZhHans, Lang::ZhHant, Lang::Ja, Lang::Ko, Lang::De, Lang::Fr, Lang::Es, Lang::Ru];

    pub fn code(self) -> &'static str {
        match self {
            Lang::En => "en",
            Lang::ZhHans => "zh-Hans",
            Lang::ZhHant => "zh-Hant",
            Lang::Ja => "ja",
            Lang::Ko => "ko",
            Lang::De => "de",
            Lang::Fr => "fr",
            Lang::Es => "es",
            Lang::Ru => "ru",
        }
    }

    pub fn native_name(self) -> &'static str {
        match self {
            Lang::En => "English",
            Lang::ZhHans => "简体中文",
            Lang::ZhHant => "繁體中文",
            Lang::Ja => "日本語",
            Lang::Ko => "한국어",
            Lang::De => "Deutsch",
            Lang::Fr => "Français",
            Lang::Es => "Español",
            Lang::Ru => "Русский",
        }
    }

    pub fn from_code(code: &str) -> Option<Lang> {
        Lang::ALL.iter().copied().find(|l| l.code().eq_ignore_ascii_case(code))
    }

    /// The language of the game's own settings (`l_simp_chinese`, …); None for one this window has no text for.
    pub fn from_game(code: &str) -> Option<Lang> {
        Some(match code {
            "l_english" => Lang::En,
            "l_simp_chinese" => Lang::ZhHans,
            "l_traditional_chinese" => Lang::ZhHant,
            "l_japanese" => Lang::Ja,
            "l_korean" => Lang::Ko,
            "l_german" => Lang::De,
            "l_french" => Lang::Fr,
            "l_spanish" => Lang::Es,
            "l_russian" => Lang::Ru,
            _ => return None,
        })
    }
}

/// `language` of `pdx_settings.txt` in the game's data folder.
pub fn game_language(data_dir: &std::path::Path) -> Option<Lang> {
    let text = std::fs::read_to_string(data_dir.join("pdx_settings.txt")).ok()?;
    let at = text.find("\"language\"")?;
    let rest = &text[at..];
    let v = rest.find("value=\"")? + 7;
    let end = rest[v..].find('"')?;
    Lang::from_game(&rest[v..v + end])
}

type Table = &'static [(&'static str, &'static str)];

fn table(lang: Lang) -> Table {
    match lang {
        Lang::En => EN,
        Lang::ZhHans => ZH_HANS,
        Lang::ZhHant => ZH_HANT,
        Lang::Ja => JA,
        Lang::Ko => KO,
        Lang::De => DE,
        Lang::Fr => FR,
        Lang::Es => ES,
        Lang::Ru => RU,
    }
}

pub fn tr(lang: Lang, key: &str) -> &'static str {
    let find = |t: Table| t.iter().find(|(k, _)| *k == key).map(|(_, v)| *v);
    find(table(lang)).or_else(|| find(EN)).unwrap_or("?")
}

pub fn tr_args(lang: Lang, key: &str, args: &[&str]) -> String {
    let mut s = tr(lang, key).to_string();
    for (i, a) in args.iter().enumerate() {
        s = s.replace(&format!("{{{i}}}"), a);
    }
    s
}

