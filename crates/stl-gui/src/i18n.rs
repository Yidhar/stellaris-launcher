#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_language_has_every_key_and_the_same_placeholders() {
        for lang in Lang::ALL {
            let t = table(lang);
            for (k, en) in EN {
                let Some((_, text)) = t.iter().find(|(kk, _)| kk == k) else { panic!("{} is missing {k}", lang.code()) };
                for p in ["{0}", "{1}"] {
                    assert_eq!(en.contains(p), text.contains(p), "{} {k}: placeholder {p}", lang.code());
                }
                assert!(!text.is_empty(), "{} {k} is empty", lang.code());
            }
            assert_eq!(t.len(), EN.len(), "{} has keys English does not", lang.code());
        }
    }

    #[test]
    fn substitutes_arguments_and_falls_back() {
        assert_eq!(tr_args(Lang::En, "play.status_running", &["42"]), "Stellaris is running · pid 42");
        assert_eq!(tr(Lang::En, "no.such.key"), "?");
        assert_eq!(Lang::from_game("l_simp_chinese"), Some(Lang::ZhHans));
        assert_eq!(Lang::from_game("l_polish"), None);
        assert_eq!(Lang::from_code("ZH-HANT"), Some(Lang::ZhHant));
    }
}
